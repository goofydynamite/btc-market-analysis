"""Build the star schema (sql/schema/*.sql), run every analytical query (sql/queries/*.sql)
against data/processed/btc.sqlite, and write the results to reports/sql_results.md so
reviewers can read them without running anything."""
from __future__ import annotations

import sqlite3
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
DB = ROOT / "data" / "processed" / "btc.sqlite"
OUT = ROOT / "reports" / "sql_results.md"


def to_markdown(df: pd.DataFrame) -> str:
    """Minimal markdown table (avoids an extra dependency on `tabulate`)."""
    cells = df.astype(object).where(df.notna(), "").astype(str)
    lines = ["| " + " | ".join(df.columns) + " |", "|" + "---|" * len(df.columns)]
    lines += ["| " + " | ".join(row) + " |" for row in cells.to_numpy()]
    return "\n".join(lines)


def header_comment(sql: str) -> str:
    comment = []
    for line in sql.splitlines():
        if not line.startswith("--"):
            break
        comment.append(line.lstrip("- ").strip())
    return " ".join(c for c in comment if c)


def build_schema(con: sqlite3.Connection) -> pd.DataFrame:
    for path in sorted((ROOT / "sql" / "schema").glob("*.sql")):
        con.executescript(path.read_text(encoding="utf-8"))
    tables = ["dim_date", "dim_halving_cycle", "fact_daily_price", "fact_hourly_trading"]
    return pd.DataFrame({"table": tables,
                         "rows": [con.execute(f"SELECT COUNT(*) FROM {t}").fetchone()[0] for t in tables]})


def run_queries(con: sqlite3.Connection) -> dict[str, pd.DataFrame]:
    return {p.name: pd.read_sql_query(p.read_text(encoding="utf-8"), con) for p in sorted((ROOT / "sql" / "queries").glob("*.sql"))}


def main() -> None:
    with sqlite3.connect(DB) as con:
        counts = build_schema(con)
        results = run_queries(con)
    parts = ["# SQL results\n",
             f"Generated by `src/run_sql.py` against `{DB.relative_to(ROOT).as_posix()}`.\n",
             "## Star schema (`sql/schema/01_star_schema.sql`)\n",
             "`dim_date` and `dim_halving_cycle` describe each day; `fact_daily_price` (one row per UTC day) and "
             "`fact_hourly_trading` (one row per UTC hour) hold the measures. Views `v_daily` / `v_hourly` "
             "pre-join them for analysis.\n", to_markdown(counts), ""]
    for name, df in results.items():
        sql = (ROOT / "sql" / "queries" / name).read_text(encoding="utf-8")
        parts += [f"\n## {name}\n", f"_{header_comment(sql)}_\n", to_markdown(df), ""]
        print(f"{name}: {len(df)} rows")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"-> {OUT}")


if __name__ == "__main__":
    main()
